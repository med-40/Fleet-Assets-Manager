from sqlalchemy import Column
from sqlalchemy import Date
from sqlalchemy import ForeignKey
from sqlalchemy import Integer
from sqlalchemy import String

from app.database.base import Base


class Battery(Base):

    __tablename__ = "batteries"

    # =====================================================
    # المعرف
    # =====================================================

    id = Column(
        Integer,
        primary_key=True
    )

    # =====================================================
    # العتاد المرتبطة به البطارية
    # =====================================================

    equipment_id = Column(
        Integer,
        ForeignKey("equipment.id")
    )

    # =====================================================
    # الرقم التسلسلي
    # =====================================================

    serial_number = Column(
        String(100),
        unique=True
    )

    # =====================================================
    # العلامة التجارية
    # =====================================================

    brand = Column(
        String(100)
    )

    # =====================================================
    # السعة (Ah)
    # =====================================================

    capacity = Column(
        String(50)
    )

    # =====================================================
    # تاريخ التركيب
    # =====================================================

    installation_date = Column(
        Date
    )

    # =====================================================
    # تاريخ انتهاء الضمان
    # =====================================================

    warranty_expiry_date = Column(
        Date
    )

    # =====================================================
    # الحالة
    # =====================================================

    status = Column(
        String(50),
        default="Active"
    )
