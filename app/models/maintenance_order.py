from sqlalchemy import Column
from sqlalchemy import Date
from sqlalchemy import ForeignKey
from sqlalchemy import Integer
from sqlalchemy import String
from sqlalchemy.orm import relationship

from app.database.base import Base


class MaintenanceOrder(Base):

    __tablename__ = "maintenance_orders"

    id = Column(
        Integer,
        primary_key=True
    )

    # =====================================================
    # العتاد
    # =====================================================

    equipment_id = Column(
        Integer,
        ForeignKey("equipment.id"),
        nullable=False
    )

    # =====================================================
    # خطة الصيانة
    # =====================================================
    #
    # إذا كانت العملية مرتبطة بخطة صيانة مبرمجة،
    # نحفظ رقم الخطة هنا.
    #
    # إذا كانت صيانة طارئة غير مرتبطة بخطة،
    # يمكن أن تكون القيمة فارغة.
    #
    # =====================================================

    maintenance_schedule_id = Column(
        Integer,
        ForeignKey("maintenance_schedules.id"),
        nullable=True
    )

    # =====================================================
    # نوع / اسم العملية
    # =====================================================
    #
    # يبقى هذا الحقل لتسجيل وصف العملية عند الحاجة،
    # خصوصًا للصيانة الطارئة.
    #
    # في الصيانة المبرمجة لا نعتمد عليه لتحديد الخطة،
    # بل نعتمد على maintenance_schedule_id.
    #
    # =====================================================

    maintenance_type = Column(
        String(100),
        nullable=False
    )

    # =====================================================
    # وصف العمل أو العطل
    # =====================================================

    description = Column(
        String(500)
    )

    # =====================================================
    # تاريخ بدء الصيانة
    # =====================================================

    maintenance_date = Column(
        Date
    )

    # =====================================================
    # تاريخ انتهاء الصيانة
    # =====================================================

    completion_date = Column(
        Date
    )

    # =====================================================
    # قراءة العداد عند تنفيذ الصيانة
    # =====================================================
    #
    # مثال:
    # تغيير الزيت تم عند 120000 كم.
    #
    # هذه القراءة تخص عملية الصيانة نفسها.
    #
    # =====================================================

    meter_reading = Column(
        Integer
    )

    # =====================================================
    # حالة الصيانة
    # =====================================================
    #
    # جارية / منتهية / ملغاة
    #
    # =====================================================

    status = Column(
        String(50),
        default="جارية",
        nullable=False
    )

    # =====================================================
    # الملاحظات
    # =====================================================

    notes = Column(
        String(500)
    )

    # =====================================================
    # العلاقات
    # =====================================================

    equipment = relationship(
        "Equipment",
        back_populates="maintenance_orders"
    )

    maintenance_schedule = relationship(
        "MaintenanceSchedule",
        back_populates="maintenance_orders"
    )
