from sqlalchemy import Column
from sqlalchemy import Date
from sqlalchemy import ForeignKey
from sqlalchemy import Integer
from sqlalchemy import String
from sqlalchemy.orm import relationship

from app.database.base import Base


class MaintenanceSchedule(Base):

    __tablename__ = "maintenance_schedules"

    id = Column(
        Integer,
        primary_key=True
    )

    # =====================================================
    # العتاد
    # =====================================================

    equipment_id = Column(
        Integer,
        ForeignKey("equipment.id"),
        nullable=False
    )

    # =====================================================
    # تعريف عملية الصيانة
    # =====================================================
    #
    # هذا هو اسم العملية الذي يحدده المستخدم.
    #
    # مثال:
    # تغيير زيت المحرك
    # تغيير فلتر الهواء
    # فحص الفرامل
    # فحص الإطارات
    #
    # لا توجد قائمة ثابتة يفرضها البرنامج.
    #
    # =====================================================

    name = Column(
        String(150),
        nullable=False
    )

    # =====================================================
    # دورية الصيانة بالعداد
    # =====================================================

    interval_km = Column(
        Integer
    )

    # =====================================================
    # دورية الصيانة بالأيام
    # =====================================================

    interval_days = Column(
        Integer
    )

    # =====================================================
    # آخر تاريخ تم فيه تنفيذ هذه الخطة
    # =====================================================

    last_maintenance_date = Column(
        Date
    )

    # =====================================================
    # موعد الاستحقاق القادم حسب التاريخ
    # =====================================================

    next_due_date = Column(
        Date
    )

    # =====================================================
    # وصف وشروط العملية
    # =====================================================
    #
    # يكتب المستخدم هنا شروط العملية حسب نوع العتاد.
    #
    # مثال:
    # "كل 10,000 كم أو 6 أشهر"
    #
    # أو:
    # "يتم تغيير الزيت عند ظهور المؤشر..."
    #
    # =====================================================

    description = Column(
        String(500)
    )

    # =====================================================
    # العلاقات
    # =====================================================

    equipment = relationship(
        "Equipment"
    )

    maintenance_orders = relationship(
        "MaintenanceOrder"
    )
