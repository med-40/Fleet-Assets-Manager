from sqlalchemy import Column
from sqlalchemy import Date
from sqlalchemy import ForeignKey
from sqlalchemy import Integer
from sqlalchemy import String
from sqlalchemy.orm import relationship

from app.database.base import Base


class MaintenanceSchedule(Base):

    __tablename__ = "maintenance_schedules"

    id = Column(
        Integer,
        primary_key=True
    )

    # =====================================================
    # العتاد
    # =====================================================

    equipment_id = Column(
        Integer,
        ForeignKey("equipment.id"),
        nullable=False
    )

    # =====================================================
    # اسم عملية الصيانة
    # =====================================================
    #
    # يحدده المستخدم حسب نوع وطراز العتاد.
    #
    # أمثلة:
    # تغيير زيت المحرك
    # تغيير فلتر الهواء
    # فحص الفرامل
    # تشحيم
    # فحص الإطارات
    #
    # لا توجد قائمة ثابتة يفرضها البرنامج.
    # =====================================================

    name = Column(
        String(150),
        nullable=False
    )

    # =====================================================
    # شرط الصيانة بالعداد
    # =====================================================

    interval_km = Column(
        Integer
    )

    # =====================================================
    # شرط الصيانة بالأيام
    # =====================================================

    interval_days = Column(
        Integer
    )

    # =====================================================
    # آخر تاريخ تم فيه تنفيذ هذه الخطة
    # =====================================================

    last_maintenance_date = Column(
        Date
    )

    # =====================================================
    # موعد الصيانة القادم حسب التاريخ
    # =====================================================

    next_due_date = Column(
        Date
    )

    # =====================================================
    # آخر قراءة عداد تم عندها تنفيذ الخطة
    # =====================================================
    #
    # مثال:
    #
    # تغيير الزيت تم عند 120000 كم
    #
    # هنا:
    # last_maintenance_meter = 120000
    #
    # =====================================================

    last_maintenance_meter = Column(
        Integer
    )

    # =====================================================
    # قراءة العداد التي عندها تصبح الصيانة مستحقة
    # =====================================================
    #
    # مثال:
    #
    # آخر تنفيذ = 120000
    # الفاصل = 10000
    #
    # next_due_meter = 130000
    #
    # =====================================================

    next_due_meter = Column(
        Integer
    )

    # =====================================================
    # وصف وشروط العملية
    # =====================================================
    #
    # يكتب المستخدم تفاصيل خاصة بالعملية والعتاد.
    #
    # =====================================================

    description = Column(
        String(500)
    )

    # =====================================================
    # العلاقة مع العتاد
    # =====================================================

    equipment = relationship(
        "Equipment",
        back_populates="maintenance_schedules"
    )
